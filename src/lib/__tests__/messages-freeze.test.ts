describe("message catalog freeze (wave2 regression guard)", () => {
  it("en and zh-CN carry the exact same key set", () => {
    expect(zhKeys).toEqual(enKeys);
  });

  it("the catalog key set matches the frozen snapshot", () => {
    expect(enKeys).toEqual(EXPECTED_KEYS);
  });

  it("critical keys shipped by earlier PRs are all present", () => {
    // keys that were once silently deleted by a stale overlay (never again)
    const critical = [
      "app.loadFailed",
      "app.loadFailedBody",
      "app.retry",
      "app.exportErrors.emptyPage",
      "canvas.audioTooLarge",
      "canvas.importedAudio",
      "canvas.importedTexts",
      "canvas.audioClipAria",
      "app.loadingCanvas",
      "generated.page",
    ];
    const have = new Set(enKeys);
    for (const key of critical) {
      expect(have.has(key), `${key} missing from en.json`).toBe(true);
      expect(zhKeys.includes(key), `${key} missing from zh-CN.json`).toBe(true);
    }
  });
});
