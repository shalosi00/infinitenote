/**
 * Themes gallery (issue #55) — pure accent-theme catalog + storage helpers.
 *
 * The app already ships light/dark modes (next-themes toggling the `dark`
 * class on <html>). A "theme" here is an accent layer on top of that: a
 * small set of CSS-variable overrides published in globals.css under
 * `[data-theme="…"]` (and `[data-theme="…"].dark`), applied by setting the
 * `data-theme` attribute on <html>. The default theme defines no overrides —
 * it IS the shipped look — so applying it simply clears the attribute.
 *
 * This module is deliberately pure (no React, no DOM at import time): the
 * catalog, the storage parsing and the pre-hydration script source are all
 * unit-testable. The two DOM touchpoints are:
 * - themes-dialog.tsx (user interaction: apply + persist on click)
 * - the inline pre-hydration script in app/layout.tsx (restores the stored
 *   theme before first paint, generated by themePreloadScript() so the
 *   logic cannot drift between the two call sites)
 */

export const THEME_IDS = [
  "default",
  "ocean",
  "forest",
  "sunset",
  "rose",
  "slate",
] as const;

export type ThemeId = (typeof THEME_IDS)[number];

export const DEFAULT_THEME: ThemeId = "default";

export const THEME_STORAGE_KEY = "infinitenote.theme";

/** The CSS variables a theme may override (accent set — see globals.css). */
export interface ThemeVars {
  primary: string;
  primaryForeground: string;
  ring: string;
  sidebarPrimary: string;
  sidebarRing: string;
}

export interface ThemeDefinition {
  id: ThemeId;
  /** Light-mode accent overrides (oklch values, same format as globals.css). */
  light: Partial<ThemeVars>;
  /** Dark-mode accent overrides. */
  dark: Partial<ThemeVars>;
  /** Hex swatch colors for the gallery preview (light + dark modes). */
  preview: { light: string; dark: string };
}

/** The camelCase keys of ThemeVars that every non-default theme must define. */
