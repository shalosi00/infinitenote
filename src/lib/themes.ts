/** The variable set a theme overrides, as CSS custom property names. */
export function themeVarNames(): string[] {
  return ACCENT_VAR_KEYS.map((key) => `--${key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`);
}

/** Narrow an arbitrary value (e.g. from localStorage) to a ThemeId. */
export function isThemeId(value: unknown): value is ThemeId {
  return typeof value === "string" && (THEME_IDS as readonly string[]).includes(value);
}

/**
 * Parse a stored raw value into a ThemeId. Anything missing, malformed or
 * unknown falls back to the default — a stale storage key must never break
 * boot. Mirrors the tolerance philosophy of lib/i18n.ts.
 */
export function parseStoredTheme(raw: string | null | undefined): ThemeId {
  if (typeof raw !== "string") return DEFAULT_THEME;
  const trimmed = raw.trim();
  return isThemeId(trimmed) ? trimmed : DEFAULT_THEME;
}

/**
 * Apply a theme to a document by toggling the data-theme attribute on the
 * root element. The default clears the attribute so the :root palette in
 * globals.css wins. Kept DOM-touching-but-trivial and dependency-free so it
 * can be asserted with a tiny fake in unit tests.
 */
export function applyThemeToDocument(doc: Document, id: ThemeId): void {
  if (id === DEFAULT_THEME) {
    doc.documentElement.removeAttribute("data-theme");
  } else {
    doc.documentElement.setAttribute("data-theme", id);
  }
}

/**
 * Source of the inline pre-hydration script that restores the persisted
 * theme before first paint (avoids a light→accent flash on reload). Single
 * line, wrapped in try/catch, and defensive about the stored value:
 * only clean lowercase ids that differ from the default are applied, so a
 * tampered storage value can at worst set a harmless data attribute.
 */
export function themePreloadScript(): string {
  return (
    `(function(){try{var t=localStorage.getItem(${JSON.stringify(THEME_STORAGE_KEY)});` +
    `if(typeof t==="string"&&t!==${JSON.stringify(DEFAULT_THEME)}` +
    `&&/^[a-z][a-z0-9-]*$/.test(t)){document.documentElement.setAttribute("data-theme",t)}}` +
    `catch(e){}})()`
  );
}
